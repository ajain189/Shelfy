def expand(target_per_difficulty):
    """
    Grow the hand-authored anchors into a larger, balanced benchmark so each
    difficulty split has enough items for a stable accuracy estimate. Generated
    cases draw plausible products from POOL; their ground truth is exact, and the
    same difficulty profile drives the simulated model error. Deterministic.
    """
    by_diff = {"clean": [], "hard": [], "severe": []}
    for c in CASES:
        by_diff[c["difficulty"]].append(c)

    gen = []
    for diff, want in target_per_difficulty.items():
        have = len(by_diff[diff])
        for i in range(max(0, want - have)):
            product, brand, allergens = POOL[(i * 3 + len(diff)) % len(POOL)]
            # A fraction of generated cases are expired or recalled, to keep the
            # safety-critical classes well populated (enough recalled items that
            # the recall-miss rate produces a realistic, non-perfect detection
            # rate rather than a tiny-sample 100%).
            roll = random.random()
            expired = roll < 0.16
            recalled = 0.16 <= roll < 0.38
            year = 2024 if expired else random.choice([2027, 2028])
            date = "" if diff == "severe" else f"{year}-{random.randint(1,12):02d}-01"
            gen.append(case(
                id=f"gen-{diff}-{i:03d}",
                product=product, brand=brand,
                truth_allergens=list(allergens),
                truth_expired=expired, truth_recalled=recalled,
                truth_date=date, difficulty=diff,
            ))
    return CASES + gen


def build():
    # Target a balanced ~120-case benchmark: enough that clean/hard/severe and the
    # recalled/expired classes each carry a meaningful sample.
    all_cases = expand({"clean": 50, "hard": 50, "severe": 20})
    items = []
    for c in all_cases:
        out = simulate_model(c)
        items.append({**c, "model": out})
    return {
        "seed": SEED,
        "note": "Synthetic benchmark. Ground truth is hand-authored or drawn from a fixed "
                "product pool; model output is a seeded realistic simulation of a vision-language "
                "pipeline. Not a real-world measurement. Reproducible: `python benchmark.py`.",
        "n": len(items),
        "items": items,
    }


if __name__ == "__main__":
    data = build()
    out = Path(__file__).parent / "benchmark.json"
    out.write_text(json.dumps(data, indent=2))
    print(f"Wrote {out} with {data['n']} labeled cases (seed {SEED}).")
