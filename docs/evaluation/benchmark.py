# Per-difficulty behavior of the simulated vision model. These rates are chosen
# to be realistic for label OCR + extraction, NOT flattering. They are the
# single place "how good is the model" is encoded, so they're easy to audit.
PROFILE = {
    #              date_err  allergen_miss  recall_miss  conf_mean  conf_jitter
    "clean":  dict(date_err=0.04, allergen_miss=0.04, recall_miss=0.05, conf_mean=0.93, conf_jitter=0.04),
    "hard":   dict(date_err=0.16, allergen_miss=0.12, recall_miss=0.11, conf_mean=0.82, conf_jitter=0.08),
    "severe": dict(date_err=0.80, allergen_miss=0.42, recall_miss=0.22, conf_mean=0.44, conf_jitter=0.13),
}


def simulate_model(c):
    """
    Produce a realistic model output for a ground-truth case. The model is good
    but imperfect; crucially, when it MIS-READS it tends to be LESS confident,
    the calibration that lets confidence-gated escalation work.

    Each item draws from its OWN seeded RNG (keyed by its id) rather than a single
    shared stream. This keeps the benchmark fully deterministic while ensuring the
    per-difficulty error rates actually manifest across the dataset, instead of an
    unlucky global draw order suppressing every rare event.
    """
    rng = random.Random(f"{SEED}:{c['id']}")
    p = PROFILE[c["difficulty"]]
    correct = True

    # Allergen extraction: on hard/severe labels the model occasionally misses one.
    pred_allergens = list(c["truth_allergens"])
    if c["truth_allergens"] and rng.random() < p["allergen_miss"]:
        pred_allergens.pop(rng.randrange(len(pred_allergens)))
        correct = False

    # Date reading: misread → either wrong date or no date.
    date_ok = True
    if rng.random() < p["date_err"]:
        date_ok = False
        correct = False

    # Recall matching queries openFDA by the READ brand/product. It can miss a
    # real recall when the brand was matched too loosely or the firm name differs
    # from the label. Crucially this miss is INDEPENDENT of legibility: a recall
    # can be missed on a label the model otherwise read confidently, which is the
    # dangerous "confident but wrong" case that the confidence gate cannot catch.
    # This is what makes recall detection realistically below 100%.
    pred_recalled = c["truth_recalled"]
    recall_missed = c["truth_recalled"] and rng.random() < p["recall_miss"]
    if recall_missed:
        pred_recalled = False

    # Confidence: centered on the difficulty mean, pulled DOWN when the read was
    # wrong (the realistic correlation that makes calibration meaningful).
    conf = rng.gauss(p["conf_mean"], p["conf_jitter"])
    if not correct:
        conf -= 0.18
    conf = max(0.05, min(0.99, conf))

    # The model also self-reports legibility trouble on hard/severe labels.
    legibility_note = c["difficulty"] in ("severe",) or (c["difficulty"] == "hard" and not correct)

    return dict(
        pred_allergens=pred_allergens,
        date_ok=date_ok,
        pred_recalled=pred_recalled,
        confidence=round(conf, 3),
        legibility_note=legibility_note,
        allergen_correct=(set(pred_allergens) == set(c["truth_allergens"])),
        date_correct=date_ok,
        fully_correct=correct,
    )


